// Bundle directories have a known user-facing file type. Ordinary folders with an
// extension-like name must still be folders (for example a folder named photos.jpg).
const bundleCategories: Record<string, FileCategory> = {
  app: 'installer',
  pages: 'document',
  numbers: 'spreadsheet',
  key: 'presentation',
  band: 'audio',
  logicx: 'audio',
  photoslibrary: 'image',
};
export function category(entry: Pick<Entry, 'name' | 'directory'>): FileCategory {
  const name = entry.name.toLowerCase();
  const extension = name.includes('.') ? name.slice(name.lastIndexOf('.') + 1) : '';
  if (entry.directory) return bundleCategories[extension] ?? 'folder';
  if (namedFiles[name]) return namedFiles[name];
  // Try compound extensions first; plain names without a dot are not extensions.
  const dot = name.indexOf('.');
  if (dot < 0) return 'other';
  const parts = name.slice(dot + 1).split('.');
  for (let i = 0; i < parts.length; i++) {
    const found = extensionCategories.get(parts.slice(i).join('.'));
    if (found) return found;
  }
  return 'other';
}
